# ------------------------------------------------------------------ 3. Retrieval and generation
heading("3. Retrieval and generation evaluation", 1)
table("Table R0. Data separation (split by context, seed 42)", ["Split", "Contexts", "Questions", "Use"], [
    ("Training", tr["contexts"], f"{tr['questions']:,}", "Fine-tuning"),
    ("Validation", va["contexts"], va["questions"], "Epoch selection (T5-base)"),
    ("Test", te["contexts"], te["questions"], "All reported metrics, scored once"),
])
note("No context occurs in more than one split. A random split by question would place the answer of "
     f"{pct(split['leakage_if_random_question_split']['test_questions_with_same_fact_seen_in_train'])} of test questions "
     "in the training set.")
names = {"dense_minilm": "Dense (MiniLM + FAISS, cosine)", "lexical_tfidf_char": "Lexical (char 3–5-gram TF-IDF)",
         "hybrid": "Hybrid (0.5 dense + 0.5 lexical)"}
rows = []
for sp, lab in (("val", "Validation"), ("test", "Test")):
    for k, n in names.items():
        m = ret[sp][k]
        rows.append((lab, n, m["queries"], *(f"{f3(m[x])} {ci3(m[x + '_95ci'])}" for x in ("recall@1", "recall@3", "recall@5", "mrr"))))
table("Table R2. Retrieval of the gold context (index of all 103 contexts)",
      ["Split", "Retriever", "Questions", "Recall@1", "Recall@3", "Recall@5", "MRR"], rows)
note("95% CIs are bootstrap intervals resampling whole contexts. Hybrid weights were fixed a priori, not tuned on test data.")

ctx = {"gold": "Gold context", "top1": "Retrieved top-1 (hybrid)", "top3": "Retrieved top-3 (hybrid)"}
rows = []
for name, g in gens:
    for s, lab in ctx.items():
        if s in g["test"]:
            m = g["test"][s]
            rows.append((name, lab, f"{f3(m['exact_match'])} {ci3(m['exact_match_95ci'])}", f"{f3(m['f1'])} {ci3(m['f1_95ci'])}",
                         f3(m["bleu"]), f"{f3(m['rougeL'])} {ci3(m['rougeL_95ci'])}"))
table(f"Table 4 (revised). Response generation on the held-out test split ({te['questions']} questions, {te['contexts']} unseen contexts)",
      ["Model", "Context", "Exact Match [95% CI]", "F1 [95% CI]", "BLEU", "ROUGE-L [95% CI]"], rows)
t5, phi = gens[1][1], gens[2][1]
note(f"Training on CPU: at most {t5['max_per_fact']} paraphrased questions per fact ({t5['train_questions']} training "
     f"questions). T5-base: {t5['epochs']} epochs, lr {t5['lr']:g}, batch {t5['batch_size']}, epoch {t5['selected_epoch']} "
     f"selected on validation. Phi-2 + LoRA (r = 8): {phi['epochs']} epoch, lr {phi['lr']:g}, batch {phi['batch_size']}, "
     "answer-only loss. Exact Match and F1 follow SQuAD v1.1; BLEU is corpus-level sacreBLEU (no CI); ROUGE-L is the "
     "mean F-measure. Phi-2 was not run with the top-1 context. These values replace the original Table 4 "
     "(EM 0.921 / 0.968), which could not be reproduced.")

out = ROOT / "docs" / "Revised_Evaluation_Tables.docx"
doc.save(out)
