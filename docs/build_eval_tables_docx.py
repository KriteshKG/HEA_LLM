"""Builds docs/Revised_Evaluation_Tables.docx (NER, few-shot, retrieval and generation tables) from evaluation/results."""
import json
from math import sqrt
from pathlib import Path

from docx import Document
from docx.enum.section import WD_ORIENT
from docx.enum.table import WD_TABLE_ALIGNMENT
from docx.oxml import OxmlElement
from docx.oxml.ns import qn
from docx.shared import Cm, Pt, RGBColor

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "evaluation" / "results"
J = lambda n: json.load(open(RES / n))
ner, ret, split = J("ner_checks.json"), J("retrieval_metrics.json"), J("split_summary.json")
gens = [("T5-base (no fine-tuning)", J("generation_t5_zeroshot.json")), ("T5-base (fine-tuned)", J("generation_t5.json")),
        ("Phi-2 + LoRA (fine-tuned)", J("generation_phi2.json"))]
BLUE = RGBColor(0x1F, 0x3A, 0x5F)

doc = Document()
doc.styles["Normal"].font.name, doc.styles["Normal"].font.size = "Calibri", Pt(10.5)
sec = doc.sections[0]
sec.orientation, sec.page_width, sec.page_height = WD_ORIENT.LANDSCAPE, sec.page_height, sec.page_width
sec.left_margin = sec.right_margin = Cm(1.8)


def shade(cell, fill):
    sh = OxmlElement("w:shd")
    sh.set(qn("w:val"), "clear"); sh.set(qn("w:color"), "auto"); sh.set(qn("w:fill"), fill)
    cell._tc.get_or_add_tcPr().append(sh)


def heading(text, lvl):
    for r in doc.add_heading(text, lvl).runs:
        r.font.color.rgb = BLUE


def note(text):
    r = doc.add_paragraph().add_run(text)
    r.italic, r.font.size = True, Pt(9)


def table(caption, header, rows):
    doc.add_paragraph().add_run(caption).bold = True
    t = doc.add_table(rows=1, cols=len(header)); t.style = "Table Grid"; t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for c, x in zip(t.rows[0].cells, header):
        c.text = ""; c.paragraphs[0].add_run(x).bold = True; shade(c, "D9E2F3")
    for row in rows:
        for c, x in zip(t.add_row().cells, row):
            c.text = str(x)
    for row in t.rows:
        for c in row.cells:
            for p in c.paragraphs:
                for r in p.runs:
                    r.font.size = Pt(9.5)


def wilson(k, n, z=1.96):
    p, d = k / n, 1 + z * z / n
    c, h = (p + z * z / (2 * n)) / d, z * sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return c - h, c + h


pct = lambda x: f"{100 * x:.1f}%"
ci = lambda a: f"[{100 * a[0]:.1f}, {100 * a[1]:.1f}]"
f3 = lambda x: f"{x:.3f}"
ci3 = lambda a: f"[{a[0]:.3f}, {a[1]:.3f}]"
wl, _ = ner["gold_set"]["5_of_5_abstracts_correct_wilson95"]
vg, doi = ner["value_grounding"], ner["doi"]
tr, va, te = split["train"], split["val"], split["test"]

doc.add_heading("Revised evaluation tables", 0)
note("Generated by docs/build_eval_tables_docx.py from evaluation/results/*.json (bash evaluation/run_all.sh). "
     "Table numbers follow the revised manuscript.")

# ------------------------------------------------------------------ 1. NER
heading("1. Revised NER evaluation", 1)
