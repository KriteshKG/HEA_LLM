    ("OpenAI GPT-4", "API", "0.50", "3", "93%", "0.94"),
    ("OpenAI GPT-4o", "API", "0.15", "4", "90%", "0.88"),
    ("OpenAI GPT-4o Mini", "API", "0.005", "1", "92%", "0.89"),
    ("OpenAI GPT-o1 Mini", "API", "2.50", "6", "85%", "0.87"),
    ("Gemini Pro", "API", "0.075", "3", "84%", "0.88"),
    ("DeepSeek V3", "API", "0.05", "8", "75%", "0.73"),
